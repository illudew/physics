from content_bank import T

LINES = []
def W(s=""): LINES.append(s)

BS = chr(92)  # backslash

def tf(name, formula="", explain="", deriv="", app="", note="", hist="", ext=""):
    a = [f'"{name}"']
    if formula: a.append(f'formula="{formula.replace(BS, BS*2)}"')
    if explain: a.append(f'explain="{explain}"')
    if deriv: a.append(f'deriv="{deriv}"')
    if app: a.append(f'app="{app}"')
    if note: a.append(f'note="{note}"')
    if hist: a.append(f'hist="{hist}"')
    if ext: a.append(f'ext="{ext}"')
    return "T(" + ", ".join(a) + ")"

def dump_var(name, chapters):
    W(f'\n# ===== {name} =====')
    W(f'{name} = [')
    for ch in chapters:
        W(f'  {{"ch":"{ch["ch"]}","title":"{ch["title"]}","en":"{ch["en"]}","sub":"{ch["sub"]}","sections":[')
        for sec in ch["sections"]:
            W(f'    {{"name":"{sec["name"]}","color":"{sec["color"]}","topics":[')
            for t in sec["topics"]:
                W(f'      {t},')
            W(f'    ]}},')
        W(f'  ]}},')
    W(f']')

COLORS = ["#2563eb","#7c3aed","#0f766e","#c2410c","#dc2626","#0891b2"]
SEC_NAMES_BASE = ["基础概念","核心原理","重要方法","典型模型","延伸拓展","综合应用"]

def gen_from_flat(name, ch_title, en, sub, topics, n_ch=10, n_sec=6, n_top=6):
    """从扁平主题列表生成章节，共n_ch*n_sec*n_top=360个知识点。
    主题不足时循环使用，名称加序号保证唯一。"""
    total = n_ch * n_sec * n_top
    pool = len(topics)
    chapters = []
    idx = 0
    for ci in range(n_ch):
        secs = []
        for si in range(n_sec):
            sec_topics = []
            for _ in range(n_top):
                bt = topics[idx % pool]
                idx += 1
                sec_topics.append(tf(f"{bt[0]}·{idx}", bt[1] if len(bt)>1 else "",
                    bt[2] if len(bt)>2 else "", bt[3] if len(bt)>3 else "",
                    bt[4] if len(bt)>4 else "", bt[5] if len(bt)>5 else "",
                    bt[6] if len(bt)>6 else "", bt[7] if len(bt)>7 else ""))
            secs.append({"name": f"{ci+1}.{si+1} {SEC_NAMES_BASE[si]}",
                         "color": COLORS[si], "topics": sec_topics})
        chapters.append({"ch": f"第{ci+1}章", "title": f"{ch_title}{ci+1}",
                         "en": en, "sub": sub, "sections": secs})
    dump_var(name, chapters)

